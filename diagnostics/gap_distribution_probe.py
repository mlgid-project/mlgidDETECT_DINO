"""Phase Z.6 — is the sibling GAP DISTRIBUTION what teaches the merge?

Where the sequence stands. Z.2: training this head on real frames reproduces the merge (3.22 px at an
8 px gap) where ladder frames give 0.31. Z.3: none of four properties of the real distribution --
brightness variation, rings, object count, crowding -- accounts for it. Z.4: burying the ladder's
pairs in four times as much context costs a factor of 2, not the factor of 10 needed, so it is not
about pairs dominating the frame. Z.5: up-weighting close pairs 30x buys 19% at 8 px -- real, and far
short of a fix.

What is left is the NATURE of the pairs, and `_sample_chi_gaps` (simulation.py:499-510) is where their
separations come from:

    cluster_tight_frac    = 0.32           32% of sibling gaps drawn from...
    cluster_tight_gap_px  = (1.0, 6.0)     ...1-6 px, i.e. 0.4-2.5 sigma at sigma_chi = 2.43 px
    cluster_broad_lognorm = (4.007, 0.95)  the other 68%, lognormal with median 55 px

Measured on generated frames (Z.4/Z.5): `<5 px` 0.173, `<10 px` 0.247 -- only 0.074 of gaps land in
5-10 px. Below ~3 px two peaks are genuinely unresolvable and ONE box is the correct answer; above
~20 px the job is trivial. The distribution is concentrated in both of those regimes and nearly empty
in between -- and the 8 px case the deployed model fails on sits in that hole.

TWO ARMS. Anchors: real 3.22, ladder 0.31, deployed head 3.83, same test slice as Z/Z.2/Z.3/Z.4.

  ARM 1 (does the gap distribution CAUSE it?) -- ladder frames whose pair separations are redrawn
  from the real distribution instead of the fixed 4-24 px rungs. Its control is generated by the SAME
  function with separations drawn uniformly from the rungs, so frame count, planting code, box shape,
  intensity and filtering are all identical and the gap distribution is the only variable.
      real gaps ~ 3.2, ladder gaps ~ 0.3  -> CONFIRMED, the gap distribution is the cause.
      both ~ 0.3                          -> refuted; the ladder's pairs teach resolution whatever
                                             their separations, and the difference is elsewhere again.

  ARM 2 (is it FIXABLE from the config?) -- real frames with `cluster_tight_gap_px` widened, which
  moves the tight component INTO the resolvable band without touching anything else:
      (1, 6)   the shipped value, i.e. the Z.2 baseline re-run here
      (4, 12)
      (6, 20)
      merge weakens with widening -> a data-side lever on a knob that ALREADY EXISTS, and the first
      thing in this whole sequence that could go into a real training run unchanged.
      flat -> the gap distribution is not the lever either, whatever arm 1 says about cause.

The realised gap statistics of every training set are measured and printed -- `<5 px`, the 5-10 px
band, and the median -- so the dose is read off the data rather than assumed from the config.

CAVEAT built in: real gaps have a long tail (lognormal median 55 px), and a pair cannot be planted
wider than the frame allows, so arm 1 clamps draws at 100 px and reports the clamped fraction.

GPU, ~50 min. See tmp_diag/run_gapdist.sbatch.
"""
