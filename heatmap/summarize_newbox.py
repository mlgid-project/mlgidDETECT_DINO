"""Regenerates hm_runs/newbox/results_table_newbox.md and hm_runs/newbox/curves/ from the run directories (no hand-edited numbers).

  python heatmap/summarize_newbox.py [--runs_dir /mnt/DATA/mlgidDETECT_DINO_HEATMAP/hm_runs]

NEW convention only: box = centre +- 1 sigma (--box_coef 2,2 and variants), evaluation on the visibility-fixed files in newbox_visfix.
  (a) runs retrained on the new files: every hm_* folder directly in <runs_dir>/newbox/ that has an evaluate_final.txt
  (b) 'old checkpoint on new files': every folder in <runs_dir>/newbox/old_on_new/ (evaluate.py + score_sweep.py of an old-convention
      checkpoint on the new files), with the old AP of the same checkpoint read from its old run folder (found via runs_layout.run_dirs)
  (c) how to read: the numbers in the text are computed here from (a) and (b).
results_table.md (summarize_runs.py) stays old-convention only; runs_layout.run_dirs does not scan newbox/, so the two never mix.
Curves: the newbox runs are linked into a scratch folder and plot_all_curves.py is run on it; the result is copied to newbox/curves/.
"""
import os, re, sys, json, argparse, statistics as st, shutil, subprocess

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from runs_layout import run_dirs  # noqa: E402

RUNS = '/mnt/DATA/mlgidDETECT_DINO_HEATMAP/hm_runs'
MD5 = {'organic_labeled.h5': ('organics_visfix.h5', '39ae5381ea86cbe5763d44e5a291f325', '8 frames / 817 GT'),
       '41.h5': ('perovskites_nan_wedge_visfix.h5', '4b7d168c2170e2f8d9e5e85645950805', '41 frames / 1678 GT')}
PROTO = '+nms (class-aware NMS), score floor 0.1, top-225, QMatcher min_iou 0.1'


def parse_eval(path, ds):
    """+nms numbers of dataset ds ('organic' / '41') from an evaluate_final.txt: AP, and score>0.3 recall/prec/ring/FP."""
    t = open(path).read()
    i = t.index(f'[hm+nms] {ds}:'); seg = t[i:i + 1500]
    d = {'ap': float(re.search(r'ap_total ([0-9.]+)', seg).group(1))}
    m = re.search(r'score>0\.3: recall ([0-9.]+) \(seg ([0-9.]+), ring ([0-9.]+)\) precision ([0-9.]+) preds (\d+) FP (\d+)', seg)
    if m:
        d.update(rec=float(m.group(1)), ring=float(m.group(3)), prec=float(m.group(4)), fp=int(m.group(6)))
    return d


def sweep_floor(path, ds, floor, topk=225):
    """AP at a score floor from a score_sweep.log (decode nms, top-K topk); None if absent."""
    if not os.path.exists(path):
        return None
    t = open(path).read()
    m = re.search(rf'=== {re.escape(ds)} \([^)]*\) \| decode nms \| top-K {topk} ===(.*?)(?:\n===|\Z)', t, re.S)
    if not m:
        return None
    m2 = re.search(rf'floor {floor}\s+: AP ([0-9.]+)', m.group(1))
    return float(m2.group(1)) if m2 else None


def train_info(rdir):
    a = {}
    try:
        a = json.load(open(os.path.join(rdir, 'args.json')))
    except Exception:
        pass
    log = os.path.join(rdir, 'train.log')
    spe, last = None, None
    if os.path.exists(log):
        t = open(log).read()
        v = [int(x) for x in re.findall(r'^\[epoch \d+\] loss .*\((\d+)s\)\s*$', t, re.M)]
        spe = st.median(v) if v else None
        e = re.findall(r'^\[epoch (\d+)\] loss', t, re.M)
        last = int(e[-1]) if e else None
    return a, spe, last


def f4(x):
    return '-' if x is None else f'{x:.4f}'


def f3(x):
    return '-' if x is None else f'{x:.3f}'


def label(a, name):
    kind = 'run C recipe (bs 8 x 125, lr 4.2e-4, drops 90/112)' if a.get('lr_drops') else 'plain H1 recipe (bs 4 x 250, lr 3e-4, drop 45)'
    return kind


def method(name):
    return 'run C recipe' if '_long_' in name else 'plain tf32 recipe'


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--runs_dir', default=RUNS); ap.add_argument('--no_curves', action='store_true')
    a = ap.parse_args()
    nb = os.path.join(a.runs_dir, 'newbox')
    rel = lambda p: os.path.relpath(p, a.runs_dir)
    runs = [(r, os.path.join(nb, r)) for r in sorted(os.listdir(nb)) if r.startswith('hm_') and os.path.isdir(os.path.join(nb, r))]
    done, other = [], []
    for r, d in runs:
        (done if os.path.exists(os.path.join(d, 'evaluate_final.txt')) else other).append((r, d))
    recs = []
    for r, d in done:
        args, spe, last = train_info(d)
        o, v = parse_eval(os.path.join(d, 'evaluate_final.txt'), 'organic'), parse_eval(os.path.join(d, 'evaluate_final.txt'), '41')
        sw = os.path.join(d, 'score_sweep.log')
        recs.append(dict(run=r, dir=rel(d), args=args, spe=spe, o=o, v=v, v02=sweep_floor(sw, '41', '0.2'), o02=sweep_floor(sw, 'organic', '0.2')))
    recs.sort(key=lambda x: (str(x['args'].get('box_coef')) != '2,2', x['args'].get('lr_drops') is not None, x['args'].get('box_coef', ''), x['args'].get('seed', 0)))

    L = ['# Heatmap detector, group "newbox": NEW box convention (box = centre +- 1 sigma) on the re-fitted validation files', '',
         'Generated by `heatmap/summarize_newbox.py` from the run folders in `hm_runs/newbox/` (no hand-edited numbers). `results_table.md` holds the OLD convention only; the two are never mixed.', '',
         '- **Training boxes**: `--box_coef a,w` = a_coef,w_coef in sigma units as FULL extent; `2,2` = box centre +- 1 sigma (new convention). Old convention: 2.80,1.30 with the old, wrongly scaled validation widths.',
         f'- **Data** (`HM_DATA_DIR=~/Documents/datasets/validationsSets/newbox_visfix`, visibility-fixed copies; clamp patch for infinite ring angle_width in `util/pygidloader.py`, overhanging boxes are kept): ' +
         '; '.join(f'`{k}` = {v[0]}, md5 {v[1]}, {v[2]}' for k, v in MD5.items()) + '. The raw uploads (wrong visibility) are not used.',
         f'- **Evaluation protocol** (all numbers): {PROTO}; AP columns are the +nms headline; recall / precision / FP use score > 0.3; "41 f0.2" = 41-set AP at score floor 0.2 (top-225, from `score_sweep.log`). Frozen SimMIM swin, ridge ring target, TF32, legacy simulator unless noted.', '',
         '## (a) Retrained on the new files', '',
         '| Run | Recipe | Seed | box_coef | Epochs | s/epoch | AP org | AP 41 | 41 f0.2 | Recall org | Prec org | FP org | Recall 41 | Prec 41 | FP 41 | Data | Run dir |',
         '|:--|:--|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|:--|']
    data = f'visfix {MD5["organic_labeled.h5"][1][:8]} / {MD5["41.h5"][1][:8]}'
    for x in recs:
        ag = x['args']
        L.append(f"| {x['run']} | {label(ag, x['run'])} | {ag.get('seed', '-')} | {ag.get('box_coef', '-')} | {ag.get('epochs', '-')} | {'-' if x['spe'] is None else int(x['spe'])} | "
                 f"{f4(x['o']['ap'])} | {f4(x['v']['ap'])} | {f4(x['v02'])} | {f3(x['o'].get('rec'))} | {f3(x['o'].get('prec'))} | {x['o'].get('fp', '-')} | "
                 f"{f3(x['v'].get('rec'))} | {f3(x['v'].get('prec'))} | {x['v'].get('fp', '-')} | {data} | `{x['dir']}` |")
    if not recs:
        L.append('| (no finished run yet) |' + ' |' * 16)
    # mean/spread of recipes that exist with several seeds at the same box_coef
    grp = {}
    for x in recs:
        grp.setdefault((label(x['args'], x['run']), x['args'].get('box_coef')), []).append(x)
    multi = [(k, v) for k, v in grp.items() if len(v) > 1]
    if multi:
        L += ['', '**Seed groups** (mean ± SD over the seeds, same recipe and box_coef):', '']
        for (lab, bc), v in multi:
            def ms(key, sub):
                vals = [y[sub][key] for y in v if key in y[sub]]
                return f'{st.mean(vals):.4f} ± {st.stdev(vals):.4f}' if len(vals) > 1 else f4(vals[0] if vals else None)
            v02 = [y['v02'] for y in v if y['v02'] is not None]
            L.append(f"- {lab}, box_coef {bc}, n={len(v)} (seeds {', '.join(str(y['args'].get('seed')) for y in v)}): AP org {ms('ap', 'o')} (range {min(y['o']['ap'] for y in v):.4f}-{max(y['o']['ap'] for y in v):.4f}), "
                     f"AP 41 {ms('ap', 'v')} (range {min(y['v']['ap'] for y in v):.4f}-{max(y['v']['ap'] for y in v):.4f}), 41 f0.2 " +
                     (f'{st.mean(v02):.4f} ± {st.stdev(v02):.4f}' if len(v02) > 1 else f4(v02[0] if v02 else None)))
    if other:
        L += ['', '**Folders without evaluate_final.txt** (running, failed or skipped; see `hm_runs/_tools/queue7_status.txt` / `queue8_status.txt`):', '']
        for r, d in other:
            _, _, last = train_info(d)
            L.append(f'- `{rel(d)}`: last training epoch in train.log = {last if last is not None else "none"}')
    notes = []
    for q in ('queue7_status.txt', 'queue8_status.txt'):
        p = os.path.join(a.runs_dir, '_tools', q)
        if os.path.exists(p):
            notes += [f'{q}: {l}' for l in open(p).read().splitlines() if re.search(r'SKIP [a-z]*\s*hm_.*would not|FAILED|failed, continuing', l)]
    if notes:
        L += ['', '**Queue notes (failures / skipped runs)**:', ''] + [f'- {n}' for n in notes]

    # (b) old checkpoints on the new files
    oon = os.path.join(nb, 'old_on_new')
    old_map = dict(run_dirs(a.runs_dir))
    L += ['', '## (b) Old checkpoint on new files (inference only, no retraining)', '',
          'Checkpoints trained with the OLD convention (box_coef 2.80,1.30 on the legacy simulator), scored on the new files with their own box output (box_coef is not used at inference). '
          '"old" = the same checkpoint on the old files (its old `evaluate_final.txt`, same protocol), "new" = on `newbox_visfix`. Same eval protocol as (a). Outputs in `newbox/old_on_new/<run>/`, produced by `heatmap/eval_old_on_new.sh`.', '',
          '| Checkpoint (old run) | Method | Seed | box_coef (training) | AP org old | AP org new | AP 41 old | AP 41 new | 41 f0.2 new | Recall org new | Prec org new | FP org new | Recall 41 new | Prec 41 new | FP 41 new | Data (new) | Old run dir | Output dir |',
          '|:--|:--|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|:--|:--|']
    oon_rows = []
    if os.path.isdir(oon):
        for r in sorted(os.listdir(oon)):
            d = os.path.join(oon, r); ev = os.path.join(d, 'evaluate_final.txt')
            if not (r.startswith('hm_') and os.path.exists(ev)):
                continue
            od = old_map.get(r)
            oargs, _, _ = train_info(od) if od else ({}, None, None)
            try:
                oo, ov = parse_eval(os.path.join(od, 'evaluate_final.txt'), 'organic'), parse_eval(os.path.join(od, 'evaluate_final.txt'), '41')
            except Exception:
                oo = ov = {'ap': None}
            no, nv = parse_eval(ev, 'organic'), parse_eval(ev, '41')
            f02 = sweep_floor(os.path.join(d, 'score_sweep.log'), '41', '0.2')
            seed = oargs.get('seed', '-')
            oon_rows.append(dict(run=r, method=method(r), seed=seed, oo=oo['ap'], no=no['ap'], ov=ov['ap'], nv=nv['ap'], f02=f02))
            L.append(f"| {r} | {method(r)} | {seed} | {oargs.get('box_coef', '-')} | {f4(oo['ap'])} | {f4(no['ap'])} | {f4(ov['ap'])} | {f4(nv['ap'])} | {f4(f02)} | {f3(no.get('rec'))} | {f3(no.get('prec'))} | {no.get('fp', '-')} | "
                     f"{f3(nv.get('rec'))} | {f3(nv.get('prec'))} | {nv.get('fp', '-')} | {data} | `{rel(od) if od else '?'}` | `{rel(d)}` |")
    meth = {}
    for x in oon_rows:
        meth.setdefault(x['method'], []).append(x)
    if meth:
        L += ['', '**Per-method means** (old -> new; mean over the checkpoints listed above):', '']
        for k, v in meth.items():
            m = lambda key: st.mean(y[key] for y in v)
            sd = lambda key: (st.stdev(y[key] for y in v) if len(v) > 1 else float('nan'))
            L.append(f"- {k}, n={len(v)}: AP org {m('oo'):.4f} -> {m('no'):.4f}; AP 41 {m('ov'):.4f} -> {m('nv'):.4f} (SD on new {sd('nv'):.4f}); 41 f0.2 new {m('f02'):.4f}")

    # (c) how to read, numbers computed from (a)/(b)
    L += ['', '## (c) How to read this table', '',
          '- Old-convention APs (`results_table.md`) are NOT comparable with the APs here: the validation boxes were re-fitted (stored widths are now 2 sigma, drawn box = centre +- sigma) and the visibility was fixed. Compare only within this file.']
    if meth:
        alls = [y for v in meth.values() for y in v]
        dv = st.mean(y['ov'] for y in alls) - st.mean(y['nv'] for y in alls)
        do = st.mean(y['oo'] for y in alls) - st.mean(y['no'] for y in alls)
        L.append(f"- The 41-set drop is the new ground truth, not the model: the {len(alls)} old checkpoints lose {dv:.3f} AP on the 41 set ({st.mean(y['ov'] for y in alls):.4f} -> {st.mean(y['nv'] for y in alls):.4f}) "
                 f"and {do:.3f} on organic ({st.mean(y['oo'] for y in alls):.4f} -> {st.mean(y['no'] for y in alls):.4f}) without any retraining. (The galvani session reports that the old DINO checkpoint loses the same on its side; not measured here.)")
        base = [x for x in recs if x['args'].get('box_coef') == '2,2']
        for k, v in meth.items():
            rb = [x for x in base if method(x['run']) == k]
            if rb:
                nvm = st.mean(y['nv'] for y in v)
                sdv = st.stdev(y['nv'] for y in v) if len(v) > 1 else float('nan')
                best = ', '.join(f"seed {x['args'].get('seed')}: {x['v']['ap']:.4f}" for x in rb)
                L.append(f"- Retraining at +-1 sigma ({k}, box_coef 2,2) vs the old checkpoints of the same method on the new files (41 mean {nvm:.4f}, n={len(v)}, SD {sdv:.4f}): retrained 41 AP {best}; "
                         f"difference of the mean retrained 41 AP to the old-checkpoint mean {st.mean(x['v']['ap'] for x in rb) - nvm:+.4f} (retrained n={len(rb)}).")
    L += ['- Seed spread matters: the old checkpoints are n=3 per method; a retrained run with a single seed differs from them by less than ~2 SD only if it lies inside the old range. Rows with n=1 are single seeds.',
          '- organic has 8 frames / 817 GT: epoch-to-epoch AP varies by several 0.01 during training, so only the final-checkpoint numbers of `evaluate_final.txt` are used.']
    txt = '\n'.join(L) + '\n'
    open(os.path.join(nb, 'results_table_newbox.md'), 'w').write(txt)
    print(txt)

    if not a.no_curves and runs:
        view = os.path.join(a.runs_dir, '_scratch', 'newbox_view')
        shutil.rmtree(view, ignore_errors=True); os.makedirs(view)
        for r, d in done:
            os.symlink(d, os.path.join(view, r))
        pc = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'plot_all_curves.py')
        subprocess.run([sys.executable, pc, '--runs_dir', view], check=False, stdout=subprocess.DEVNULL)
        out = os.path.join(nb, 'curves')
        shutil.rmtree(out, ignore_errors=True)
        if os.path.isdir(os.path.join(view, 'curves')):
            shutil.copytree(os.path.join(view, 'curves'), out)
            print(f'curves -> {out}', file=sys.stderr)


if __name__ == '__main__':
    main()
